-- На відміну від api_key_hash (нам достатньо звірити, що прислав мерчант, з
-- хешем - незворотність тут перевага, а не проблема), секрет вебхука
-- застосунок мусить уміти ПРОЧИТАТИ: саме ним ми самі підписуємо кожне
-- вихідне повідомлення. Хеш тут не підійшов би - ним неможливо підписати
-- нічого. Тому явний текст, той самий компроміс, що й для будь-якого
-- секрету, яким система користується як клієнт, а не лише перевіряє як сервер.
alter table merchants add column webhook_secret text;

-- Демо-мерчант із V3 отримує фіксований секрет, як і його API-ключ - працює
-- лише проти локальної бази, засіяної цією ж міграцією, тож публікація його
-- тут не є витоком реального секрету.
update merchants
   set webhook_secret = 'demo-webhook-secret-do-not-use-in-production'
 where id = '00000000-0000-0000-0000-000000000001';

alter table merchants alter column webhook_secret set not null;
